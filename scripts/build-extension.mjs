// Bundle the pure core into the extension as one ES module.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
await build({
  entryPoints: [path.join(root, "src/extension-core.ts")],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: ["chrome110"],
  outfile: path.join(root, "integrations/browser-extension/core.js"),
  legalComments: "none",
  banner: { js: "// Generated by scripts/build-extension.mjs from src/core. Do not edit by hand." },
});
console.log("integrations/browser-extension/core.js written");
